const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const fs=require('node:fs');
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||undefined,args:['--no-sandbox','--disable-dev-shm-usage']});
  const output=process.env.SCREENSHOT_DIR||'/tmp/bom-site-regression';fs.mkdirSync(output,{recursive:true});
  try{
    const p=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
    p.on('pageerror',e=>errors.push(e.message));p.on('console',m=>{if(['warning','error'].includes(m.type()))errors.push(m.text());});
    await p.goto(pathToFileURL(path.resolve(__dirname,'../index.html')).href);
    const step=i=>p.locator(`[data-step="${i}"]`).click();
    const layer=name=>p.locator(`[data-detail-tab="${name}"]`).click();
    const shot=name=>p.screenshot({path:path.join(output,name+'.png')});
    assert.equal(await p.locator('#site-stage').inputValue(),'Under construction');
    await p.locator('#site-stage').selectOption('Planned');await step(1);await step(0);
    assert.equal(await p.locator('#site-stage').inputValue(),'Planned');
    assert.match(await p.locator('#save-state').innerText(),/unsaved/);
    await p.locator('#save-site').click();
    await p.locator('#restart').click();
    await shot('job');
    await step(1);await p.locator('[data-layout-tab="Site"]').click();
    assert.equal(await p.locator('#site-pool').inputValue(),'Planned');
    await p.locator('#site-poolRole').selectOption('Pool enclosure');
    await p.locator('[data-pool-ref="street"]').check();await p.locator('#save-site').click();
    await shot('pool');
    await step(5);await p.locator('#preview-package').click();
    assert.match(await p.locator('#package-content').innerText(),/Office pool-safety review required/);
    assert.match(await p.locator('#package-content').innerText(),/finished ground levels/);
    await p.keyboard.press('Escape');
    await step(2);await p.locator('[data-select="side"]').click();await layer('Base');
    assert.equal(await p.locator('#base').inputValue(),'Masonry wall');
    assert.equal(await p.locator('#profile-baseStart').inputValue(),'0.6');
    assert.ok(await p.locator('#side [data-base="side"]').count()>0);
    await shot('base');
    await p.locator('#profile-baseShape').selectOption('Level top');await p.locator('#save-details').click();
    assert.equal(await p.locator('#form-error').innerText(),'');
    const level=await p.locator('#side [data-base="side"]').first().getAttribute('points');
    const points=level.split(' ').map(pair=>pair.split(',').map(Number));
    assert.ok(Math.abs(points[2][1]-points[3][1])<0.001,'Wall top must be level');
    await p.locator('#profile-baseStart').fill('0.1');await p.locator('#save-details').click();
    assert.match(await p.locator('#form-error').innerText(),/below the ground/);
    await step(5);await p.locator('#preview-package').click();
    assert.match(await p.locator('#package-content').innerText(),/0.6 m start; 0.3 m end/);
    assert.match(await p.locator('#package-content').innerText(),/unsaved profile draft/);
    await p.keyboard.press('Escape');await step(2);await layer('Base');
    assert.equal(await p.locator('#profile-baseStart').inputValue(),'0.1');
    await p.locator('#profile-baseStart').fill('0.6');
    await p.locator('#profile-baseShape').selectOption('Sloped top');
    await p.locator('#profile-baseEnd').fill('0.9');await p.locator('#save-details').click();
    await layer('Ground');await p.locator('#profile-ground').selectOption('Step');
    await p.locator('#profile-rise').fill('0.2');await p.locator('#save-details').click();
    assert.ok(await p.locator('#side [data-ground="side"]').count()>1);
    await shot('ground');
    await layer('Base');await p.locator('#profile-baseShape').selectOption('Stepped top');
    await p.locator('#save-details').click();assert.equal(await p.locator('#form-error').innerText(),'');
    await layer('Fence');await p.locator('#profile-top').selectOption('Level top');
    await p.locator('#save-details').click();
    const topPoints=await p.locator('#side [data-fence="side"]').evaluateAll(els=>els.map(el=>el.getAttribute('points').split(' ').slice(2).map(pair=>+pair.split(',')[1])).flat());
    assert.ok(Math.max(...topPoints)-Math.min(...topPoints)<0.01);
    await p.locator('#profile-top').selectOption('Stepped top');await p.locator('#save-details').click();
    await shot('fence');
    await layer('Ground');await p.locator('#profile-ground').selectOption('Unmeasured');await p.locator('#save-details').click();
    assert.ok(await p.locator('#side [data-ground="side"]').first().getAttribute('stroke-dasharray'));
    await step(4);await p.locator('[data-source="message"]').click();
    assert.match(await p.locator('#source-view').innerText(),/No live connection/);
    await p.locator('#add-note').click();
    assert.equal(await p.locator('#note-scope').inputValue(),'gate');
    await p.locator('#note-kind').selectOption('Customer message');
    await p.locator('#note-source').selectOption('message');
    await p.locator('#note-text').fill('Confirm clearance after the path is poured.');
    await p.locator('#save-note').click();
    assert.match(await p.locator('#linked-notes').innerText(),/Street gate/);
    assert.match(await p.locator('#linked-notes').innerText(),/Confirm clearance/);
    await shot('note');
    await step(2);assert.doesNotMatch(await p.locator('#linked-notes').innerText(),/Confirm clearance/);
    await step(3);await p.locator('#add-note').click();
    await p.locator('#note-text').fill('Confirm revised height on this range.');await p.locator('#save-note').click();
    assert.match(await p.locator('#linked-notes').innerText(),/3-8 m/);
    await p.locator('#range-start').fill('4');await step(5);
    await p.locator('#preview-package').click();
    assert.match(await p.locator('#package-content').innerText(),/Street A-B \/ 3-8 m/);
    assert.match(await p.locator('#package-content').innerText(),/Sold facts \/ signed sources/);
    assert.match(await p.locator('#package-content').innerText(),/Recorded site \/ measured versus planned/);
    assert.match(await p.locator('#package-content').innerText(),/Confirm clearance/);
    await p.locator('#handover-dialog').evaluate(el=>el.scrollTo(0,el.scrollHeight));await shot('handover-site');
    await p.keyboard.press('Escape');
    for(const width of [1280,1440,1600,1920]){
      await p.setViewportSize({width,height:1100});await step(2);await layer('Base');
      assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
      const overlap=await p.evaluate(()=>document.querySelector('#profile-summary').getBoundingClientRect().bottom>document.querySelector('.workspace-bottom').getBoundingClientRect().top);
      assert.equal(overlap,false,'Profile must not overlap footer');
      await shot(width+'-base');
    }
    assert.deepEqual(errors,[]);console.log('PASS: site drafts, planned pool, base/ground/fence profiles, validation, scoped notes, source provenance and handover at four desktop widths.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
